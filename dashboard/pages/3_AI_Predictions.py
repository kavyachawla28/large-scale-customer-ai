import streamlit as st
import pandas as pd
import plotly.express as px


# ---------------------------------------------------------
# Page configuration
# ---------------------------------------------------------
st.set_page_config(
    page_title="AI Predictions",
    page_icon="🤖",
    layout="wide",
)


# ---------------------------------------------------------
# Load churn predictions
# ---------------------------------------------------------
@st.cache_data
def load_churn_data():
    path = "data/processed/powerbi_churn_predictions.parquet"
    return pd.read_parquet(path)


churn = load_churn_data()


# ---------------------------------------------------------
# Header
# ---------------------------------------------------------
st.title("🤖 AI Predictions")
st.caption("Machine-learning based customer churn risk analysis")

st.markdown(
    """
    This page presents churn-risk predictions generated by the
    Random Forest classification pipeline.
    """
)


# ---------------------------------------------------------
# Sidebar
# ---------------------------------------------------------
st.sidebar.header("AI Filters")

risk_levels = sorted(churn["risk_level"].unique())

selected_risk = st.sidebar.multiselect(
    "Risk Level",
    risk_levels,
    default=risk_levels,
)

filtered = churn[
    churn["risk_level"].isin(selected_risk)
].copy()


# ---------------------------------------------------------
# KPI calculations
# ---------------------------------------------------------
total_customers = len(filtered)

high_risk = (filtered["risk_level"] == "High Risk").sum()

medium_risk = (filtered["risk_level"] == "Medium Risk").sum()

low_risk = (filtered["risk_level"] == "Low Risk").sum()

average_probability = filtered["churn_probability"].mean()


# ---------------------------------------------------------
# KPI cards
# ---------------------------------------------------------
col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric(
        "Customers Analyzed",
        f"{total_customers:,}",
    )

with col2:
    st.metric(
        "High Risk",
        f"{high_risk:,}",
    )

with col3:
    st.metric(
        "Medium Risk",
        f"{medium_risk:,}",
    )

with col4:
    st.metric(
        "Avg. Churn Probability",
        f"{average_probability:.1%}",
    )


st.divider()


# ---------------------------------------------------------
# Risk Distribution
# ---------------------------------------------------------
risk_data = (
    filtered
    .groupby("risk_level")
    .size()
    .reset_index(name="customers")
)

risk_order = [
    "Low Risk",
    "Medium Risk",
    "High Risk",
]

risk_data["risk_level"] = pd.Categorical(
    risk_data["risk_level"],
    categories=risk_order,
    ordered=True,
)

risk_data = risk_data.sort_values("risk_level")


fig_risk = px.bar(
    risk_data,
    x="risk_level",
    y="customers",
    text="customers",
    title="Customer Churn Risk Distribution",
    labels={
        "risk_level": "Risk Level",
        "customers": "Customers",
    },
)

fig_risk.update_traces(
    texttemplate="%{text:,}",
    textposition="outside",
)

fig_risk.update_layout(
    height=420,
)

st.plotly_chart(
    fig_risk,
    width="stretch",
)


# ---------------------------------------------------------
# Churn Probability Distribution
# ---------------------------------------------------------
fig_probability = px.histogram(
    filtered,
    x="churn_probability",
    nbins=30,
    title="Churn Probability Distribution",
    labels={
        "churn_probability": "Predicted Churn Probability",
        "count": "Customers",
    },
)

fig_probability.update_layout(
    height=420,
)

st.plotly_chart(
    fig_probability,
    width="stretch",
)


# ---------------------------------------------------------
# Model Performance
# ---------------------------------------------------------
st.subheader("Model Performance")

metric1, metric2, metric3 = st.columns(3)

with metric1:
    st.metric(
        "ROC-AUC",
        "0.6372",
    )

with metric2:
    st.metric(
        "Accuracy",
        "83.0%",
    )

with metric3:
    st.metric(
        "Churn Recall",
        "94.0%",
    )

st.caption(
    "Evaluation metrics are from the held-out synthetic test dataset."
)


# ---------------------------------------------------------
# Feature Importance
# ---------------------------------------------------------
st.subheader("Random Forest Feature Importance")

importance = pd.DataFrame(
    {
        "feature": [
            "avg_session_duration",
            "days_since_last_purchase",
            "total_spend",
            "avg_order_value",
            "avg_discount",
            "avg_pages_viewed",
            "total_quantity",
            "total_transactions",
            "active_months",
            "category_count",
        ],
        "importance": [
            0.164317,
            0.158029,
            0.152279,
            0.147302,
            0.115196,
            0.108084,
            0.060935,
            0.035056,
            0.031823,
            0.026980,
        ],
    }
).sort_values("importance", ascending=True)


fig_importance = px.bar(
    importance,
    x="importance",
    y="feature",
    orientation="h",
    title="Random Forest Feature Importance",
    labels={
        "importance": "Importance",
        "feature": "Customer Feature",
    },
)

fig_importance.update_layout(
    height=500,
)

st.plotly_chart(
    fig_importance,
    width="stretch",
)


# ---------------------------------------------------------
# High-risk customers
# ---------------------------------------------------------
st.subheader("High-Risk Customers")

high_risk_customers = (
    filtered[
        filtered["risk_level"] == "High Risk"
    ]
    .sort_values(
        "churn_probability",
        ascending=False,
    )
    .head(20)
)

display_columns = [
    "customer_id",
    "total_spend",
    "total_transactions",
    "avg_order_value",
    "days_since_last_purchase",
    "churn_probability",
    "risk_level",
]

display_data = high_risk_customers[display_columns].copy()

display_data["total_spend"] = display_data[
    "total_spend"
].round(2)

display_data["avg_order_value"] = display_data[
    "avg_order_value"
].round(2)

display_data["churn_probability"] = (
    display_data["churn_probability"] * 100
).round(1)

display_data = display_data.rename(
    columns={
        "customer_id": "Customer ID",
        "total_spend": "Total Spend",
        "total_transactions": "Transactions",
        "avg_order_value": "Avg Order Value",
        "days_since_last_purchase": "Days Since Last Purchase",
        "churn_probability": "Churn Probability (%)",
        "risk_level": "Risk Level",
    }
)

st.dataframe(
    display_data,
    width="stretch",
    hide_index=True,
)


# ---------------------------------------------------------
# Model limitation
# ---------------------------------------------------------
st.info(
    "Important: the churn target was generated from historical "
    "synthetic customer behavior for this project. Model "
    "predictions demonstrate the ML pipeline and should not "
    "be interpreted as real-world customer churn ground truth."
)